-- Q4 Construir um script que exibe o nome do projeto e a descrição de seu status atual. Para apresentar estas informações é necessário juntar as tabelas EBA_PROJECTS e EBA_PROJECT_STATUS.

SELECT
    P.NAME AS PROJECT_NAME,
    S.DESCRIPTION AS STATUS_DESCRIPTION
FROM EBA_PROJECTS P
INNER JOIN EBA_PROJECT_STATUS S
    ON P.STATUS_ID = S.ID
ORDER BY P.NAME;

-- Q5 Construir um script que apresenta o código da tarefa, nome e número total de tarefas cadastradas para cada projeto. A listagem de ser agrupada pelo PROJECT_ID.

SELECT
    P.ID AS PROJECT_ID,
    P.NAME AS PROJECT_NAME,
    COUNT(T.ID) AS TOTAL_TASKS
FROM EBA_PROJECTS P
LEFT JOIN EBA_PROJECT_TASKS T
    ON P.ID = T.PROJECT_ID
GROUP BY
    P.ID,
    P.NAME
ORDER BY
    P.ID;

-- Q6 Construir um script que liste os líderes de cada projeto (PROJECT_LEAD) cujo somatório dos orçamentos (BUDGET) dos seus projetos ultrapasse o valor de 100.000

SELECT
    PROJECT_LEAD,
    SUM(BUDGET) AS TOTAL_BUDGET
FROM EBA_PROJECTS
GROUP BY PROJECT_LEAD
HAVING SUM(BUDGET) > 100000
ORDER BY TOTAL_BUDGET DESC;

