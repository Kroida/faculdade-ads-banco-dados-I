-- Q8 Criar um script que atualize as informações do custo (COST) das tarefas em 10%. Esta atualização deve ser aplicada a todas as tarefas não finalizadas (IS_COMPLETE_YN). 

UPDATE EBA_PROJECT_TASKS
SET COST = COST * 1.10
WHERE IS_COMPLETE_YN = 'N';

