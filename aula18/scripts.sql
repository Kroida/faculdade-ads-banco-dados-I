-- Q9 Criar uma tabela chamada EBA_PROJECT_EVALUATIONS para armazenar a avaliação dos projetos. Após a criar a tabela EBA_PROJECT_EVALUATIONS construir um script que faça o cadastro das avaliações. Para todos os projetos que já foram completados (COMPLETED_DATE preenchido). Este cadastro deve receber como NOTA 5, Avaliador = SISTEMA. 

CREATE TABLE EBA_PROJECT_EVALUATIONS (
    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY,
    PROJECT_ID        NUMBER NOT NULL,
    AVALIADOR         VARCHAR2(50) NOT NULL,
    NOTA              NUMBER NOT NULL,
    DATA_AVALIACAO    DATE DEFAULT SYSDATE NOT NULL,
    CREATED           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY        VARCHAR2(255) NOT NULL,
    UPDATED           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY        VARCHAR2(255) NOT NULL,

    CONSTRAINT EBA_PROJECT_EVALUATIONS_PK
        PRIMARY KEY (ID),

    CONSTRAINT EBA_PROJECT_EVAL_PROJ_FK
        FOREIGN KEY (PROJECT_ID)
        REFERENCES EBA_PROJECTS (ID),

    CONSTRAINT EBA_PROJECT_EVAL_NOTA_CHK
        CHECK (NOTA BETWEEN 0 AND 5)
);

CREATE INDEX EBA_PROJECT_EVAL_PROJ_IDX
    ON EBA_PROJECT_EVALUATIONS (PROJECT_ID);

COMMENT ON TABLE EBA_PROJECT_EVALUATIONS IS
    'Avaliações dos projetos.';

INSERT INTO EBA_PROJECT_EVALUATIONS (
    PROJECT_ID,
    AVALIADOR,
    NOTA,
    DATA_AVALIACAO,
    CREATED,
    CREATED_BY,
    UPDATED,
    UPDATED_BY
)
SELECT
    ID,
    'SISTEMA',
    5,
    SYSDATE,
    SYSTIMESTAMP,
    USER,
    SYSTIMESTAMP,
    USER
FROM EBA_PROJECTS
WHERE COMPLETED_DATE IS NOT NULL;

COMMIT;

-- Q10 Criar um script que exiba o nome da tarefa (EBA_PROJECT_TASKS), o nome do projeto associado e o nome do marco (milestone) ao qual ela pertence.

SELECT
    T.NAME AS TASK_NAME,
    P.NAME AS PROJECT_NAME,
    M.NAME AS MILESTONE_NAME
FROM EBA_PROJECT_TASKS T
INNER JOIN EBA_PROJECTS P
    ON T.PROJECT_ID = P.ID
LEFT JOIN EBA_PROJECT_MILESTONES M
    ON T.MILESTONE_ID = M.ID
ORDER BY
    P.NAME,
    M.NAME,
    T.NAME;