-- ----------------------------------------------------
-- TABELA: ESTUDANTES
-- ----------------------------------------------------
CREATE TABLE a17_Estudantes (
    id_estudante    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome            VARCHAR2(100),
    data_nascimento DATE,
    endereco        VARCHAR2(255),
    contato         VARCHAR2(50)
);

ALTER TABLE a17_Estudantes
    ADD CONSTRAINT pk_estudante PRIMARY KEY (id_estudante);

-- ----------------------------------------------------
-- TABELA: PROFESSORES
-- ----------------------------------------------------
CREATE TABLE a17_Professores (
    id_professor  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome          VARCHAR2(100),
    especialidade VARCHAR2(100),
    contato       VARCHAR2(50)
);

ALTER TABLE a17_Professores
    ADD CONSTRAINT pk_professor PRIMARY KEY (id_professor);

-- ----------------------------------------------------
-- TABELA: CURSOS
-- ----------------------------------------------------
CREATE TABLE a17_Cursos (
    id_curso     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome         VARCHAR2(100),
    descricao    VARCHAR2(2000),
    id_professor NUMBER
);

ALTER TABLE a17_Cursos
    ADD CONSTRAINT pk_curso PRIMARY KEY (id_curso);

ALTER TABLE a17_Cursos
    ADD CONSTRAINT fk_curso_professor 
        FOREIGN KEY (id_professor) 
        REFERENCES a17_Professores(id_professor);

-- ----------------------------------------------------
-- TABELA: INSTRUMENTOS
-- ----------------------------------------------------
CREATE TABLE a17_Instrumentos (
    id_instrumento NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome           VARCHAR2(100),
    tipo           VARCHAR2(50)
);

ALTER TABLE a17_Instrumentos
    ADD CONSTRAINT pk_instrumento PRIMARY KEY (id_instrumento);

-- ----------------------------------------------------
-- TABELA: SALAS
-- ----------------------------------------------------
CREATE TABLE a17_Salas (
    id_sala    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome       VARCHAR2(100),
    capacidade NUMBER
);

ALTER TABLE a17_Salas
    ADD CONSTRAINT pk_sala PRIMARY KEY (id_sala);

-- ----------------------------------------------------
-- TABELA: AULAS
-- ----------------------------------------------------
CREATE TABLE a17_Aulas (
    id_aula  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_curso NUMBER,
    id_sala  NUMBER,
    horario  TIMESTAMP -- Ajustado de DATETIME para TIMESTAMP
);

ALTER TABLE a17_Aulas
    ADD CONSTRAINT pk_aula PRIMARY KEY (id_aula);

ALTER TABLE a17_Aulas
    ADD CONSTRAINT fk_aula_curso
        FOREIGN KEY (id_curso) 
        REFERENCES a17_Cursos(id_curso);

ALTER TABLE a17_Aulas
    ADD CONSTRAINT fk_aula_sala
        FOREIGN KEY (id_sala) 
        REFERENCES a17_Salas(id_sala);

-- ----------------------------------------------------
-- TABELA: MATRICULAS
-- ----------------------------------------------------
CREATE TABLE a17_Matriculas (
    id_estudante   NUMBER,
    id_curso       NUMBER,
    data_matricula DATE
);

ALTER TABLE a17_Matriculas
    ADD CONSTRAINT pk_matricula PRIMARY KEY (id_estudante, id_curso);

ALTER TABLE a17_Matriculas
    ADD CONSTRAINT fk_matricula_estudante
        FOREIGN KEY (id_estudante)
        REFERENCES a17_Estudantes(id_estudante);

ALTER TABLE a17_Matriculas
    ADD CONSTRAINT fk_matricula_curso
        FOREIGN KEY (id_curso)
        REFERENCES a17_Cursos(id_curso);

-- ----------------------------------------------------
-- TABELA: EVENTOS
-- ----------------------------------------------------
CREATE TABLE a17_Eventos (
    id_evento   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome        VARCHAR2(100),
    descricao   VARCHAR2(2000),
    data_evento DATE,
    id_sala     NUMBER
);

ALTER TABLE a17_Eventos
    ADD CONSTRAINT pk_evento PRIMARY KEY (id_evento);

ALTER TABLE a17_Eventos
    ADD CONSTRAINT fk_evento_sala
        FOREIGN KEY (id_sala)
        REFERENCES a17_Salas(id_sala);


