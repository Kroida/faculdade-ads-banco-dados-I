-- -----------------------------------------------------------
create table BD1_nacionalidade (
    id_nacionalidade    number GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nacionalidade       varchar2(100) not null,
    sigla               char(3) not null,
    dt_cadastro         date default sysdate not null, 
    situacao            char(1) default 'A' not null,
    constraint pk_nacionalidade primary key (id_nacionalidade)
);

-- COMENTARIOS
comment on table BD1_nacionalidade 
              is 'Tabela de controle de nacionalidades.';
              
comment on column BD1_nacionalidade.id_nacionalidade
               is 'Identificador único da nacionalidade.';
comment on column BD1_nacionalidade.nacionalidade
               is 'Nome descritivo da nacionalidade.';
comment on column BD1_nacionalidade.sigla
               is 'Sigla representativa da nalicionalidade.';
comment on column BD1_nacionalidade.dt_cadastro
               is 'Data de cadastro do registro.';
comment on column BD1_nacionalidade.situacao
               is 'Situação do registro (A=Ativo/I=Inativo)';

-- -----------------------------------------------------------
create table BD1_autor (
    id_autor            number GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nome                varchar2(100) not null,
    sobrenome           varchar2(100) not null,
    dt_nascimento       date null,
    id_nacionalidade    number null,
    dt_cadastro         date default sysdate not null, 
    situacao            char(1) default 'A' not null    
);

-- ALTERAR TABELA
alter table BD1_autor
        add constraint pk_autor primary key (id_autor);

alter table BD1_autor
        add constraint fk_autor_nacionalidade 
           foreign key (id_nacionalidade) 
            references BD1_nacionalidade(id_nacionalidade);

-- CHECK CONSTRAINT
alter table BD1_autor 
  add constraint ck_situacao check (situacao in ('A','I')); 

-- INDICE       
CREATE INDEX idx_BD1_autor_fk_nacionalidade
        ON BD1_autor (id_nacionalidade);

-- -----------------------------------------------------------
